def encode_texts(text_list):
    all_ids, all_masks = [], []
    for t in text_list:
        enc = tokenizer(
            t,
            max_length=128,
            padding="max_length",
            truncation=True,
            return_tensors="pt",
        )
        all_ids.append(enc["input_ids"])
        all_masks.append(enc["attention_mask"])
    return torch.cat(all_ids), torch.cat(all_masks)

