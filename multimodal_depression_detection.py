MAX_AUDIO_LEN = 80_000  # ~5 s at 16 kHz

def load_audio(path: str, augment: bool = False) -> torch.Tensor:
    """Load wav, resample to 16 kHz, sanitise → 1-D tensor."""
    if not os.path.exists(path):
        return torch.zeros(MAX_AUDIO_LEN)
    try:
        y, sr = sf.read(path)
    except Exception:
        return torch.zeros(MAX_AUDIO_LEN)

    y = np.array(y, dtype=np.float32)
    if y.ndim > 1:
        y = y.mean(axis=1)

    y = np.nan_to_num(y, nan=0.0, posinf=0.0, neginf=0.0)

    if sr != 16000:
        y = librosa.resample(y, orig_sr=sr, target_sr=16000)

    # FIX — too short or silent files cause NaN inside Wav2Vec2 CNN layers
    if len(y) < 1600:
        return torch.zeros(MAX_AUDIO_LEN)

    peak = np.abs(y).max()
    if peak > 0:
        y = y / peak

    # Augment only during training
    if augment and np.random.rand() < 0.3:
        y = y + 0.005 * np.random.randn(*y.shape).astype(np.float32)

    y = np.nan_to_num(y, nan=0.0, posinf=1.0, neginf=-1.0)

    inputs = processor(y, sampling_rate=16000, return_tensors="pt", padding=True)
    val = inputs.input_values[0]
    val = torch.nan_to_num(val, nan=0.0, posinf=1.0, neginf=-1.0)
    return val

